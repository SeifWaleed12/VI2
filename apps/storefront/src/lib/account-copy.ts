export function accountMessage(locale: Locale, key: AccountKey) {
  return (locale === "ar" ? ar : en)[key];
}
export function accountStatus(locale: Locale, value: string) {
  const statuses = [
    "pending",
    "completed",
    "canceled",
    "archived",
    "requires_action",
    "not_paid",
    "awaiting",
    "captured",
    "partially_refunded",
    "refunded",
  ] as const;
  const key = statuses.find((status) => status === value);
  return accountMessage(locale, key ?? "unknownStatus");
}
