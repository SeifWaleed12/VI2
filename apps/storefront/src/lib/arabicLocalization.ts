export function translateArabicUi(value: string) {
  const normalized = value.replace(/\s+/g, " ").trim();
  if (!normalized) return value;
  const direct = arabicUi[normalized];
  if (direct) return direct;
  const productCount = normalized.match(/^(\d+) PRODUCTS?$/i);
  if (productCount) return `${productCount[1]} منتج`;
  const brandCount = normalized.match(/^(\d+) products?$/i);
  if (brandCount) return `${brandCount[1]} منتج`;
  const remaining = normalized.match(/^ONLY (\d+) LEFT$/i);
  if (remaining) return `متبقي ${remaining[1]} فقط`;
  const ratings = normalized.match(/^(\d+(?:[.,]\d+)?[KM]?) ratings$/i);
  if (ratings) return `${ratings[1]} تقييم`;
  const lastQuantity = normalized.match(/^LAST QTY:\s*(\d+)$/i);
  if (lastQuantity) return `آخر كمية: ${lastQuantity[1]}`;
  const deliveryRemaining = normalized.match(/^([\d,.]+) EGP TO GO$/i);
  if (deliveryRemaining) return `متبقي ${deliveryRemaining[1]} جنيه`;
  const showProducts = normalized.match(/^SHOW (\d+) PRODUCTS$/i);
  if (showProducts) return `عرض ${showProducts[1]} منتج`;
  const placeOrder = normalized.match(/^PLACE ORDER · ([\d,.]+) EGP$/i);
  if (placeOrder) return `تأكيد الطلب · ${placeOrder[1]} EGP`;
  const removeProduct = normalized.match(/^Remove (.+)$/);
  if (removeProduct) return `إزالة ${removeProduct[1]}`;
  const addProduct = normalized.match(/^Add (.+?)(?: to cart)?$/);
  if (addProduct) return `إضافة ${addProduct[1]}`;
  const viewProduct = normalized.match(/^View (.+)$/);
  if (viewProduct) return `عرض ${viewProduct[1]}`;
  const showSlide = normalized.match(/^Show slide (\d+)$/i);
  if (showSlide) return `عرض الشريحة ${showSlide[1]}`;
  const unitText = normalized
    .replace(/\bVeggie Softgels\b/g, "كبسولات نباتية هلامية")
    .replace(/\bVeggie Capsules\b/g, "كبسولات نباتية")
    .replace(/\bVeg Capsules\b/g, "كبسولات نباتية")
    .replace(/\bSoftgels\b/g, "كبسولات هلامية")
    .replace(/\bTablets\b/g, "أقراص")
    .replace(/\bCapsules\b/g, "كبسولات")
    .replace(/\bChocolate Malt\b/g, "شوكولاتة مالت")
    .replace(/\bChocolate\b/g, "شوكولاتة")
    .replace(/\bUnflavored\b/g, "دون نكهة");
  const localizedUnits = unitText.replace(/\bserving\b/gi, "حصة");
  if (localizedUnits !== normalized) return localizedUnits;
  return value;
}
